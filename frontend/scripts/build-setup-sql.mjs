// Writes supabase/MDIFY_SETUP.sql: every migration in order, in one
// transaction, for pasting into the Supabase SQL Editor. Run after changing
// a migration:  npm run sql:setup   (npm run sql:check fails when stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATIONS = path.join(REPO, 'supabase', 'migrations');
export const SETUP_FILE = path.join(REPO, 'supabase', 'MDIFY_SETUP.sql');

export function buildSetupSql() {
  const files = fs.readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort();
  const parts = files.map((f) => {
    const sql = fs.readFileSync(path.join(MIGRATIONS, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    return `-- ════ ${f} ════\n\n${sql}\n`;
  });
  return [
    '-- MDify database setup: all migrations in supabase/migrations, in order.',
    '-- Paste into Supabase Dashboard → SQL Editor → Run. One transaction: if any',
    '-- statement fails, nothing is applied. Generated by',
    '-- frontend/scripts/build-setup-sql.mjs; edit the migrations, not this file.',
    `-- Includes: ${files.join(', ')}`,
    '',
    'begin;',
    '',
    parts.join('\n'),
    'commit;',
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sql = buildSetupSql();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(SETUP_FILE) ? fs.readFileSync(SETUP_FILE, 'utf8') : '';
    if (current !== sql) {
      console.error('supabase/MDIFY_SETUP.sql is out of date: run npm run sql:setup');
      process.exit(1);
    }
    console.log('supabase/MDIFY_SETUP.sql is up to date');
  } else {
    fs.writeFileSync(SETUP_FILE, sql);
    console.log(`wrote supabase/MDIFY_SETUP.sql (${sql.length} chars)`);
  }
}
